const fs = require('fs');
const path = require('path');

/**
 * Agrega comentarios de IA a archivos Java generados automáticamente
 * Uso: node scripts/ai-code-annotator.js <archivo.java> [modelo] [fecha]
 */

function addAIComment(filePath, model = 'GPT-4', date = new Date().toISOString().split('T')[0]) {
  try {
    if (!fs.existsSync(filePath)) {
      console.error(`❌ Error: El archivo ${filePath} no existe`);
      process.exit(1);
    }

    const content = fs.readFileSync(filePath, 'utf8');
    const aiComment = `// Generated by AI on ${date} using ${model}`;
    
    // Buscar la primera línea que no sea comentario o import
    const lines = content.split('\n');
    let insertIndex = 0;
    
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim();
      if (line && !line.startsWith('//') && !line.startsWith('import') && !line.startsWith('package')) {
        insertIndex = i;
        break;
      }
    }
    
    // Insertar el comentario de IA
    lines.splice(insertIndex, 0, aiComment);
    
    // Escribir el archivo modificado
    fs.writeFileSync(filePath, lines.join('\n'));
    
    console.log(`✅ Comentario de IA agregado a ${filePath}`);
    console.log(`   Comentario: ${aiComment}`);
    
  } catch (error) {
    console.error(`❌ Error procesando archivo: ${error.message}`);
    process.exit(1);
  }
}

// Función para procesar múltiples archivos
function processDirectory(dirPath, model = 'GPT-4') {
  const files = fs.readdirSync(dirPath);
  const javaFiles = files.filter(file => file.endsWith('.java'));
  
  console.log(`📁 Procesando ${javaFiles.length} archivos Java en ${dirPath}...`);
  
  javaFiles.forEach(file => {
    const filePath = path.join(dirPath, file);
    addAIComment(filePath, model);
  });
}

// Función para detectar código generado por IA
function detectAIGeneratedCode(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  
  // Patrones que indican código generado por IA
  const aiPatterns = [
    /\/\/ Generated by AI/i,
    /\/\/ AI generated/i,
    /\/\/ This code was generated/i,
    /\/\/ Auto-generated/i
  ];
  
  return aiPatterns.some(pattern => pattern.test(content));
}

// Función para listar archivos con código generado por IA
function listAIGeneratedFiles(dirPath = '.') {
  const javaFiles = [];
  
  function scanDirectory(dir) {
    const items = fs.readdirSync(dir);
    
    items.forEach(item => {
      const itemPath = path.join(dir, item);
      const stat = fs.statSync(itemPath);
      
      if (stat.isDirectory() && !item.startsWith('.') && item !== 'node_modules') {
        scanDirectory(itemPath);
      } else if (item.endsWith('.java')) {
        javaFiles.push(itemPath);
      }
    });
  }
  
  scanDirectory(dirPath);
  
  const aiGenerated = javaFiles.filter(file => detectAIGeneratedCode(file));
  
  if (aiGenerated.length > 0) {
    console.log('🤖 Archivos con código generado por IA:');
    aiGenerated.forEach(file => {
      console.log(`   📄 ${file}`);
    });
  } else {
    console.log('📝 No se encontraron archivos con código generado por IA');
  }
  
  return aiGenerated;
}

// CLI
if (require.main === module) {
  const args = process.argv.slice(2);
  
  if (args.length === 0) {
    console.log(`
🤖 AI Code Annotator - Herramienta para comentar código generado por IA

Uso:
  node scripts/ai-code-annotator.js <archivo.java> [modelo] [fecha]
  node scripts/ai-code-annotator.js --dir <directorio> [modelo]
  node scripts/ai-code-annotator.js --list [directorio]

Ejemplos:
  node scripts/ai-code-annotator.js src/Main.java GPT-4 2024-01-15
  node scripts/ai-code-annotator.js --dir src GPT-4
  node scripts/ai-code-annotator.js --list src
    `);
    process.exit(0);
  }
  
  if (args[0] === '--list') {
    const dir = args[1] || '.';
    listAIGeneratedFiles(dir);
  } else if (args[0] === '--dir') {
    const dir = args[1];
    const model = args[2] || 'GPT-4';
    
    if (!dir) {
      console.error('❌ Error: Debes especificar un directorio');
      process.exit(1);
    }
    
    processDirectory(dir, model);
  } else {
    const filePath = args[0];
    const model = args[1] || 'GPT-4';
    const date = args[2] || new Date().toISOString().split('T')[0];
    
    addAIComment(filePath, model, date);
  }
}

module.exports = {
  addAIComment,
  processDirectory,
  detectAIGeneratedCode,
  listAIGeneratedFiles
}; 